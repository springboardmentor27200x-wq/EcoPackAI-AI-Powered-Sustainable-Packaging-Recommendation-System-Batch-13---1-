CREATE VIEW vw_top_sustainable_materials AS
SELECT
    material_id, material_name, material_type,
    biodegradability_score, co2_emission_score,
    recyclability_percentage, cost_per_kg_usd,
    ROUND((biodegradability_score * 0.4
         + recyclability_percentage * 0.3
         + (10 - LEAST(co2_emission_score, 10)) * 10 * 0.3), 2) AS sustainability_index
FROM packaging_materials
ORDER BY sustainability_index DESC;

CREATE VIEW vw_material_category_summary AS
SELECT
    pm.material_name, pm.material_type, pc.category_name,
    mcm.suitability_score, pm.cost_per_kg_usd, pm.biodegradability_score
FROM material_category_mapping mcm
JOIN packaging_materials pm ON mcm.material_id = pm.material_id
JOIN product_categories  pc ON mcm.category_id = pc.category_id;

CREATE VIEW vw_category_material_stats AS
SELECT
    pc.category_name,
    COUNT(pm.material_id)                        AS total_materials,
    ROUND(AVG(pm.biodegradability_score), 1)     AS avg_biodegradability,
    ROUND(AVG(pm.co2_emission_score), 2)         AS avg_co2,
    ROUND(AVG(pm.cost_per_kg_usd), 2)            AS avg_cost,
    ROUND(AVG(pm.recyclability_percentage), 1)   AS avg_recyclability
FROM product_categories pc
LEFT JOIN material_category_mapping mcm ON pc.category_id = mcm.category_id
LEFT JOIN packaging_materials pm        ON mcm.material_id = pm.material_id
GROUP BY pc.category_name
ORDER BY avg_biodegradability DESC;

